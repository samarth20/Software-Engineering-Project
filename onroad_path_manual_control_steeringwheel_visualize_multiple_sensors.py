def game_loop(args):
    """
    Main loop of the simulation. It handles updating all the HUD information,
    ticking the agent and, if needed, the world.
    """
    pygame.init()
    pygame.font.init()

    try:
        client = carla.Client(args.host, args.port)
        client.set_timeout(2.0)

        hud = HUD(args.width, args.height)
        world = World(client.get_world(), hud, args.filter)
        controller = DualControl(world, args.autopilot)

        sampling_resolution = 3
        sampling_resolution_optimal_line = 0.2
        grp = GlobalRoutePlanner(world.map, sampling_resolution_optimal_line)
        spawn_points = world.map.get_spawn_points()
        # Spawn point for TOWN 7
        spawn_point_1 = spawn_points[58]
        # Define the route using indices from the spawn points specified for TOWN 7
        route_1_indices = [58, 108, 113, 101, 83, 40, 87]
        # Get locations from the spawn point indices
        route_1 = [spawn_points[i].location for i in route_1_indices]
        X_route, Y_route = show_route(route_1, world, grp)

        # Logging X and Y Data for comparison and start with spawn point
        X = np.array([spawn_point_1.location.x])
        Y = np.array([spawn_point_1.location.y])
        last_location = spawn_point_1.location

        # Display Manager organize all the sensors an its display in a window
        # If can easily configure the grid and the total window size
        display_manager = DisplayManager(grid_size=[2, 3], window_size=[args.width, args.height])

        # Then, SensorManager can be used to spawn RGBCamera, LiDARs and SemanticLiDARs as needed
        # and assign each of them to a grid position,
        SensorManager(world, display_manager, 'RGBCamera',
                      carla.Transform(carla.Location(x=0, z=2.4), carla.Rotation(yaw=-90)),
                      world.player, {}, display_pos=[0, 0])
        SensorManager(world, display_manager, 'RGBCamera',
                      carla.Transform(carla.Location(x=0, z=2.4), carla.Rotation(yaw=+00)),
                      world.player, {}, display_pos=[0, 1])
        SensorManager(world, display_manager, 'RGBCamera',
                      carla.Transform(carla.Location(x=0, z=2.4), carla.Rotation(yaw=+90)),
                      world.player, {}, display_pos=[0, 2])
        SensorManager(world, display_manager, 'RGBCamera',
                      carla.Transform(carla.Location(x=0, z=2.4), carla.Rotation(yaw=180)),
                      world.player, {}, display_pos=[1, 1])
        SensorManager(world, display_manager, 'LiDAR', carla.Transform(carla.Location(x=0, z=2.4)),
                      world.player,
                      {'channels': '64', 'range': '100', 'points_per_second': '250000', 'rotation_frequency': '20'},
                      display_pos=[1, 0])
        SensorManager(world, display_manager, 'SemanticLiDAR', carla.Transform(carla.Location(x=0, z=2.4)),
                      world.player,
                      {'channels': '64', 'range': '100', 'points_per_second': '100000', 'rotation_frequency': '20'},
                      display_pos=[1, 2])

        clock = pygame.time.Clock()
        while True:
            clock.tick_busy_loop(60)
            if controller.parse_events(world, clock):
                return
            world.tick(clock)
            # Render received data
            display_manager.render()
            if world.player and world.player.get_transform().location.distance(
                    route_1[-1]) > 0.8 and world.player.get_transform().location.distance(
                last_location) > sampling_resolution:
                X = np.append(X, world.player.get_transform().location.x)
                Y = np.append(Y, world.player.get_transform().location.y)
                last_location = world.player.get_transform().location
            # print(clock.get_fps())
            pygame.display.flip()

    finally:
        if display_manager:
            display_manager.destroy()
        if world is not None:
            world.destroy()

        pygame.quit()
        time.sleep(0.5)
        plt.plot(-1 * X_route[1:], Y_route[1:], 'bo',
                 label='Optimal line')  # somehow when spawning a vehicle the coordinate (0,0) is added still unclear why???
        plt.plot(-1 * X, Y, 'ro',
                 label='Autopilot')  # somehow when spawning a vehicle the coordinate (0,0) is added still unclear why???
        plt.annotate('Start Point', xy=(-spawn_point_1.location.x, spawn_point_1.location.y),
                     xytext=(-spawn_point_1.location.x - 40, spawn_point_1.location.y),
                     arrowprops=dict(facecolor='black', shrink=0.05),
                     )
        plt.annotate('End Point', xy=(-route_1[-1].x, route_1[-1].y),
                     xytext=(-route_1[-1].x - 40, route_1[-1].y),
                     arrowprops=dict(facecolor='black', shrink=0.05),
                     )
        plt.legend()
        plt.show()
        np.savez('XY_manual_steering_wheel', X, Y)
        np.savez('XY_optimal_route', X_route, Y_route)


